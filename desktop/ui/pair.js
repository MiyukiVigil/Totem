// Pairing window: shows the QR code, then the confirmation number, then "done".
const { invoke } = window.__TAURI__.core;
const { listen } = window.__TAURI__.event;
const $ = (id) => document.getElementById(id);

function show(section) {
  for (const s of ["setup", "scan", "confirm", "done"]) $(s).classList.toggle("hidden", s !== section);
}

async function init() {
  const s = await invoke("status");
  $("relay").value = s.relay_url ?? s.suggested_relay_url;
  $("current").textContent = s.paired ? `Currently paired with ${s.phone}. Pairing again replaces it.` : "";
  $("relay-note").textContent = s.hosting_relay
    ? "Totem runs the relay on this PC. The phone needs to be on the same Wi-Fi."
    : "";
  if (s.relay_error) $("relay-note").textContent += ` Warning: ${s.relay_error}`;
}

$("relay").addEventListener("keydown", (e) => {
  if (e.key === "Enter") $("start").click();
});

$("start").addEventListener("click", async () => {
  $("error").textContent = "";
  $("start").disabled = true;
  try {
    await invoke("start_pairing", { relayUrl: $("relay").value });
  } catch (e) {
    $("error").textContent = String(e);
    show("setup");
  } finally {
    $("start").disabled = false;
  }
});

listen("pair-qr", (e) => {
  // The SVG is generated by our own Rust code from the pairing link, not from user input.
  $("qr").innerHTML = e.payload.svg;
  show("scan");
});
listen("pair-confirm", (e) => {
  $("phone").textContent = e.payload.phone;
  $("code").textContent = e.payload.code;
  show("confirm");
});
listen("pair-done", (e) => {
  $("done-text").textContent = `Paired with ${e.payload}.`;
  show("done");
});
$("close").addEventListener("click", () => window.close());

init();
